ROOT = Path(__file__).resolve().parents[1] / "Packages/VanmoCore/Sources/VanmoCore/Localization"


def swift_escape(s: str) -> str:
    return (
        s.replace("\\", "\\\\")
        .replace("\"", "\\\"")
        .replace("\n", "\\n")
    )


def write_swift():
    lines = [
        "import Foundation",
        "",
        "enum L10nTable {",
        "    static let english: [String: String] = [",
    ]
    for key in sorted(EN, key=lambda k: (k.lower(), k)):
        lines.append(f'        "{swift_escape(key)}": "{swift_escape(EN[key])}",')
    lines += [
        "    ]",
        "}",
        "",
    ]
    (ROOT / "L10nTable.swift").write_text("\n".join(lines), encoding="utf-8")


def write_xcstrings():
    strings = {}
    for key, en in EN.items():
        strings[key] = {
            "localizations": {
                "en": {
                    "stringUnit": {
                        "state": "translated",
                        "value": en,
                    }
                },
                "zh-Hans": {
                    "stringUnit": {
                        "state": "translated",
                        "value": key,
                    }
                },
            }
        }
    catalog = {
        "sourceLanguage": "zh-Hans",
        "strings": strings,
        "version": "1.0",
    }
    (ROOT / "Resources" / "Localizable.xcstrings").write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    (ROOT / "Resources").mkdir(exist_ok=True)
    write_swift()
    write_xcstrings()
    print(f"wrote {len(EN)} strings")
